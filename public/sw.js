const CACHE_NAME = 'salon-manager-cache-v56';
const APP_SHELL = [
  '/', '/index.html', '/manifest.webmanifest', '/favicon.svg', '/mask-icon.svg',
  '/apple-touch-icon.png', '/icon-192.png', '/icon-512.png', '/icon-maskable-192.png', '/icon-maskable-512.png',
];

self.addEventListener('install', (event) => {
  event.waitUntil(caches.open(CACHE_NAME).then((cache) => cache.addAll(APP_SHELL)));
  // 以前はここでself.skipWaiting()を無条件に呼んでおり、デプロイのたびに開きっぱなしの
  // タブ/PWAが更新チェックのタイミングで即座に新バージョンへ切り替わり、直後の
  // controllerchange(main.jsx)がwindow.location.reload()を無条件に実行していた——日次
  // 入力の途中でも問答無用でリロードされ、入力中のデータを失い得る設計になっていた
  // (PWAアップデート対策、要件6)。ここでskipWaiting()を呼ばないことで、新しいService
  // Workerは「待機中(waiting)」のままとどまり、ユーザーがApp.jsx側の更新バナーで
  // 明示的に「更新する」を押すまでは、開いているタブは古いバージョンのまま安全に動き
  // 続ける(下のmessageハンドラ参照)。
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches.keys().then((keys) => Promise.all(keys.filter((key) => key !== CACHE_NAME).map((key) => caches.delete(key))))
  );
  self.clients.claim();
});

// main.jsxのSwUpdateBanner「更新する」ボタンから送られる、ユーザー起点の明示的な適用指示。
// これ以外の経路(タイマー・フォーカス復帰等)でskipWaiting()を呼ぶことは無い。
self.addEventListener('message', (event) => {
  if (event.data?.type === 'SKIP_WAITING') {
    self.skipWaiting();
  }
});

self.addEventListener('fetch', (event) => {
  if (event.request.method !== 'GET') return;
  // 同一オリジン(このアプリ自身の静的ファイル)以外は一切横取りしない。Supabase等の
  // API呼び出しをこのService Workerがキャッシュ・フォールバック対象にしてしまうと、
  // ネットワークが一瞬不安定になっただけでAPIの最新レスポンスの代わりに古いレスポンスを
  // 返してしまう(下のCACHE_NAME v7コメント参照)。ここで早期returnすればブラウザが
  // 素の(Service Worker非経由の)fetchとして処理する。
  const requestUrl = new URL(event.request.url);
  if (requestUrl.origin !== self.location.origin) return;
  event.respondWith(
    // cache: 'no-store' でService Worker自身のfetchがブラウザHTTPキャッシュを経由しないように
    // する(index.html等は元々Cache-Control: max-age=0だが、念のための二重の安全策)。
    fetch(event.request, { cache: 'no-store' })
      .then((response) => {
        const copy = response.clone();
        caches.open(CACHE_NAME).then((cache) => cache.put(event.request, copy));
        return response;
      })
      .catch(() => caches.match(event.request).then((cached) => cached || caches.match('/index.html')))
  );
});
