-- 「過去月へ切り替えると初期設定案内が再表示される」不具合の根本修正。
--
-- 原因: ダッシュボードの初期設定チェックリスト(月間目標/営業日・休業日/固定費設定/日次入力の
-- 4項目)は、いずれもApp.jsx側でその月(selectedMonth)のデータが存在するかどうかだけを見て
-- 「完了」を判定していた。そのため、既に完全にセットアップ済みの店舗であっても、データの
-- 無い過去月・翌月へ対象月を切り替えた瞬間に「未完了」へ逆戻りしていた。
--
-- 対応方針: 初期設定は「対象月ごとの状態」ではなく「店舗単位で一度完了すれば恒久的に完了」
-- として管理する。company.setup(会社作成ウィザードの完了状態、company/store/admin/settings/
-- completeの5項目)とは別の概念のため、既存フィールドを流用せず、store_profiles(店舗ごとに
-- 1行、住所・電話番号等と同じ「店舗の永続的な属性」を持つ既存テーブル)へ新しい列を追加する
-- ——新しいテーブルは作らない。
--
-- 既存データへの影響: 全店舗が false(未完了)から始まる。App.jsx側で、初回セットアップ
-- チェックリストの5項目が(現在表示中の対象月で)すべて完了と判定された最初のタイミングで
-- 自動的にtrueへ更新する仕組みを追加するため、既に運用中の店舗も次回そのユーザーが通常の
-- 月(現在月等)を表示した時点で自動的にtrueになり、その後は再表示されなくなる。
alter table public.store_profiles
  add column if not exists initial_setup_completed boolean not null default false;
