-- 運営専用の検証会社(テストサロン)を安全に識別するためのフラグ(2026-09-05)。
--
-- 背景: サロンマネージャーを複数社へ販売した後、system_adminが不具合調査・修正確認のために
-- 他社(実際の契約会社)の実データ(売上・人件費・スタッフ情報等)を直接閲覧しなくても検証
-- できるよう、専用の検証会社を用意する。会社名(例: 「テストサロン」という文字列)で判定すると
-- 会社名の変更や同名の会社が別に作られた場合に誤判定するため、DB上に明確なフラグを持たせる。
--
-- このフラグはUI側の「テストサロンとして開く」ボタンの表示可否を決めるためだけに使う——
-- RLS・権限モデルは変更しない(system_adminが会社データを読み書きできる既存の範囲は
-- そのまま)。「安全な設計」の実体は、通常の契約会社にはこのボタン自体を表示しないという
-- UI側の出し分けであり、フラグはその判定材料に過ぎない。
alter table public.companies add column if not exists is_test_company boolean not null default false;
comment on column public.companies.is_test_company is '運営専用の検証会社(テストサロン)かどうか。true の会社だけがsystem_adminの「テストサロンとして開く」機能の対象になる。会社名では判定しない——このフラグだけを判定材料にすること。';

-- 既存の「テストサロン」という名前の会社(2026-09-04作成、company_admin/店舗ともまだ0件の
-- 空の会社)を、今回の運営検証環境として利用する。IDを明示的に指定しており、将来同名の会社が
-- 別に作られても誤って対象にならない。
update public.companies
set is_test_company = true
where id = 'd058858f-c094-48c3-b394-bf426e615048';

COMMIT;
